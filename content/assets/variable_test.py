# 'name'이라는 변수(상자)에 "김코딩"이라는 글자 데이터를 저장
name = "김코딩"

# 'age'라는 변수에 숫자 25를 저장
age = 25

# 변수에 저장된 값을 print()로 출력
print(name)
print(age)

city = "서울"       # 문자열 (String)
temperature = -2    # 정수 (Integer)
vision = 1.2        # 실수 (Float)

print(city)
print(temperature)
print(vision)

